"""Administrative CLI for creating an authenticated ingestion source.

Run only from a trusted environment with direct database access.
"""
import argparse
import secrets
import sys
from uuid import UUID, uuid4

from app.ingestion import Base, Source, SessionLocal, engine, token_digest


def provision(tenant_id: str, *, source_id: str | None = None) -> tuple[str, str]:
    """Create a source and return its ID and one-time bearer token."""
    tenant_id = str(UUID(tenant_id))
    source_id = str(UUID(source_id)) if source_id else str(uuid4())
    token = secrets.token_urlsafe(48)
    with SessionLocal() as db:
        db.add(Source(id=source_id, tenant_id=tenant_id,
                      token_hash=token_digest(token), enabled=True))
        db.commit()
    return source_id, token


def main() -> int:
    parser = argparse.ArgumentParser(description="Provision a development ingestion source")
    parser.add_argument("--tenant-id", required=True, help="Existing tenant UUID")
    parser.add_argument("--source-id", help="Optional source UUID; generated by default")
    parser.add_argument("--init-dev-schema", action="store_true",
                        help="Create development tables; not for production")
    args = parser.parse_args()
    try:
        if args.init_dev_schema:
            Base.metadata.create_all(engine)
        source_id, token = provision(args.tenant_id, source_id=args.source_id)
    except (ValueError, Exception) as exc:
        print(f"Source provisioning failed: {type(exc).__name__}", file=sys.stderr)
        return 1
    print(f"SOURCE_ID={source_id}")
    print(f"SOURCE_TOKEN={token}")
    print("Store this token securely; it will not be shown again.", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
